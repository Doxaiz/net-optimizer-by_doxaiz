package com.doxaiz.netoptimizer.core.util

/** Человеческие подписи качества для метрик */
object QualityText {
    fun signal(dbm: Int): String = when {
        dbm >= -80 -> "Отлично: чистый сигнал без помех"
        dbm >= -90 -> "Хорошо: стабильный приём"
        dbm >= -100 -> "Слабо: возможны скачки скорости"
        else -> "Очень слабо: ищите точку у окна"
    }

    fun ping(ms: Int): String = when {
        ms <= 40 -> "Отлично: игра и звонки идут плавно"
        ms <= 70 -> "Норма: играть можно, редкие микрофризы"
        ms <= 120 -> "Плохо: заметные лаги"
        else -> "Очень плохо: проверьте сигнал и DNS"
    }

    fun scoreVerdict(score: Int): String = when {
        score >= 85 -> "Отлично для игр и 4K"
        score >= 65 -> "Хорошо для видео и мессенджеров"
        score >= 45 -> "Есть проблемы — нажми «Улучшить»"
        else -> "Плохая связь — нужна глубокая проверка"
    }
}
